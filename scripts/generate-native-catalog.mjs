// Preserve the existing authored recipes as native data. This runs at build time;
// the application does not ship Vite, Node, a JavaScript interpreter or a WebView.
import {createServer} from 'vite';
import ts from 'typescript';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const source=resolve(root,'macos/NativeCore/Sources/DriftCore');
const resources=resolve(source,'Resources');await mkdir(resources,{recursive:true});
const schema=ts.createSourceFile('schema.ts',await readFile(resolve(root,'src/core/project/schema.ts'),'utf8'),ts.ScriptTarget.Latest,true);
const declarations=new Map(schema.statements.filter(n=>n.name).map(n=>[n.name.text,n]));
const chosen=['MotionSettings','CardSettings','MaterialSettings','LightingSettings','AtmosphereSettings','LensSettings','SoundSettings'];
const omitted=new Set(['LensSettings.presenterTreatment','SoundSettings.underVoice']);
const generated=[];
function swiftString(x){return JSON.stringify(x).replace(/\\u2028/g,'\\u{2028}').replace(/\\u2029/g,'\\u{2029}');}
function resolved(t){if(ts.isTypeReferenceNode(t)){const n=declarations.get(t.typeName.getText(schema));if(ts.isTypeAliasDeclaration(n))return resolved(n.type);}return t;}
function typeInfo(t,name){
 t=resolved(t);
 if(ts.isTypeLiteralNode(t)){emitStruct(name,t.members);return {type:name,check:x=>`try ${x}.validate()`};}
 if(ts.isUnionTypeNode(t)){
  const nullable=t.types.some(v=>v.kind===ts.SyntaxKind.NullKeyword || (ts.isLiteralTypeNode(v)&&v.literal.kind===ts.SyntaxKind.NullKeyword));
  const values=t.types.filter(v=>!(v.kind===ts.SyntaxKind.NullKeyword || (ts.isLiteralTypeNode(v)&&v.literal.kind===ts.SyntaxKind.NullKeyword)));
  if(nullable&&values.length===1){const child=typeInfo(values[0],name);return {type:child.type+'?',check:x=>`if let v=${x} { ${child.check('v')} }`};}
  const literals=values.map(v=>{if(!ts.isLiteralTypeNode(v))throw Error('Unsupported union '+name);return v.literal.getText(schema);});
  const numeric=literals.every(v=>/^-?\d+$/.test(v));
  return {type:numeric?'Double':'String',check:x=>`guard [${literals.join(',')}].contains(${x}) else { throw DriftCoreError.invalid(${swiftString('Invalid '+name)}) }`};
 }
 if(t.kind===ts.SyntaxKind.NumberKeyword)return {type:'Double',check:x=>`guard ${x}.isFinite, abs(${x}) <= 1_000_000_000 else { throw DriftCoreError.invalid(${swiftString('Invalid '+name)}) }`};
 if(t.kind===ts.SyntaxKind.BooleanKeyword)return {type:'Bool',check:()=>''};
 if(t.kind===ts.SyntaxKind.StringKeyword)return {type:'String',check:x=>`guard ${x}.utf8.count <= 256 else { throw DriftCoreError.invalid(${swiftString('Oversized '+name)}) }`};
 throw Error('Unhandled native field '+name+': '+t.getText(schema));
}
function emitStruct(name,members,originalName=name){
 const fields=members.filter(n=>ts.isPropertySignature(n)&&!omitted.has(originalName+'.'+n.name.getText(schema))).map(n=>{
  const key=n.name.getText(schema);return {key,...typeInfo(n.type,name+key[0].toUpperCase()+key.slice(1))};
 });
 const keys=fields.map(f=>swiftString(f.key)).join(',');
 const code=[`public struct ${name}: Codable, Equatable, Sendable {`,...fields.map(f=>`    public var \`${f.key}\`: ${f.type}`),
  `    enum CodingKeys: String, CodingKey { case ${fields.map(f=>'`'+f.key+'`').join(', ')} }`,
  '    public init(from decoder: any Decoder) throws {',`        try requireKeys(decoder, allowed: [${keys}])`,
  '        let c=try decoder.container(keyedBy: CodingKeys.self)',...fields.map(f=>`        self.\`${f.key}\`=try c.decode(${f.type}.self, forKey: .\`${f.key}\`)`),
  '        try validate()','    }','    public func encode(to encoder: any Encoder) throws {',
  '        var c=encoder.container(keyedBy: CodingKeys.self)',...fields.map(f=>`        try c.encode(\`${f.key}\`, forKey: .\`${f.key}\`)`),'    }',
  '    public func validate() throws {',...fields.map(f=>'        '+f.check('`'+f.key+'`')),'    }','}'];
 generated.push(code.join('\n'));
}
for(const name of chosen){const n=declarations.get(name);if(!n||!ts.isInterfaceDeclaration(n))throw Error('Missing '+name);emitStruct(name,n.members,name);}
// These types are derived from current source fields, not a legacy file reader.
await writeFile(resolve(source,'GeneratedCreativeValues.swift'),'// Generated by scripts/generate-native-catalog.mjs. Do not edit.\nimport Foundation\n\n'+generated.join('\n\n')+'\n');
const server=await createServer({root,configFile:false,server:{middlewareMode:true},logLevel:'error'});
try{
 const load=p=>server.ssrLoadModule(p);
 const defaults=await load('/src/core/project/defaults.ts');const foundation=await load('/src/core/worlds/applyWorldFoundation.ts');
 const authored=await load('/src/core/worlds/authoredWorlds.ts');const outcomes=await load('/src/core/recipes/outcomeRecipes.ts');
 const motion=await load('/src/core/recipes/motion.ts');const materials=await load('/src/core/recipes/material.ts');
 const lighting=await load('/src/core/recipes/lighting.ts');const lenses=await load('/src/core/recipes/lens.ts');
 const spatial=await load('/src/core/spatial/spatial.ts');const backgrounds=await load('/src/backgrounds.ts');
 const transitions=await load('/src/core/timeline/transitionPresets.ts');const tempo=await load('/src/core/timeline/tempoCurve.ts');
 const now='2026-09-06T00:00:00.000Z';
 const fresh=()=>outcomes.applySafeStartOutcome(foundation.applyEditorialDriftFoundation(defaults.createDefaultDriftProjectV4('native-build',now),'16:9',now));
 const strip=p=>{
  const v=Object.fromEntries(['motion','card','material','lighting','atmosphere','lens','sound'].map(k=>[k,structuredClone(p[k])]));
  delete v.lens.presenterTreatment;delete v.sound.underVoice;return v;
 };
 const baseline=fresh();baseline.card.aspectWidth=25.76;baseline.card.aspectHeight=10.8;baseline.card.defaultFit='contain';
 const worlds=[];
 for(const world of authored.AUTHORED_WORLDS)for(const pressure of ['restrained','directed','fever'])for(const scene of [-1,0,1]){
  const p=fresh();authored.applyAuthoredWorld(p,world.id,pressure,scene<0?'16:9':'9:16',Math.max(0,scene),0);
  worlds.push({id:`${world.id}/${pressure}/${scene}`,worldID:world.id,label:world.name,pressure,scene,values:strip(p)});
 }
 const recipes=[];
 const add=(category,list,apply)=>{for(const item of list){const p=fresh();apply(p,item.id);recipes.push({id:category+'/'+item.id,category,recipeID:item.id,label:item.name??item.label??item.id,values:strip(p)});}};
 add('path',spatial.PATH_RECIPES,spatial.applyPathRecipe);add('cadence',motion.EDITORIAL_CUTS,motion.applyEditorialCut);
 add('performance',motion.PERFORMANCE_RECIPES,motion.applyPerformanceRecipe);add('character',motion.MOTION_CHARACTERS,motion.applyMotionCharacter);
 add('material',materials.MATERIAL_RECIPES,materials.applyMaterialRecipe);add('finish',materials.FINISH_RECIPES,materials.applyFinishRecipe);
 add('lighting',lighting.LIGHTING_RECIPES,lighting.applyLightingRecipe);add('lens',lenses.LENS_RECIPES,lenses.applyLensRecipe);
 const catalog={defaults:strip(baseline),worlds,recipes,backgrounds:backgrounds.BACKGROUND_STUDIES,backgroundCompositions:backgrounds.BACKGROUND_COMPOSITIONS,transitions:transitions.TRANSITION_PRESETS,tempos:tempo.TEMPO_CURVE_PRESETS};
 await writeFile(resolve(resources,'CreativeCatalog.json'),JSON.stringify(catalog));
 console.log(`Native catalog: ${worlds.length} world variants, ${recipes.length} recipes; generated ${generated.length} typed structures.`);
}finally{await server.close();}
